/**
 * The text to show for a server error. In English the server's own message is
 * kept (it is English and often more specific); in any other language a known
 * code is translated. Unknown codes fall back to the server message.
 */
export function localizeApiError(code: string | undefined, serverMessage: string | undefined): string | undefined {
  const key = code !== undefined ? (API_ERROR_KEYS as Record<string, MessageKey>)[code] : undefined;
  if (activeLanguage() === 'en' && serverMessage) return serverMessage;
  return key ? t(key) : serverMessage;
}
